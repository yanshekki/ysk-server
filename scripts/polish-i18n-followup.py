from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def flat(o: object, p: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    if isinstance(o, dict):
        for k, v in o.items():
            np = f"{p}.{k}" if p else k
            if isinstance(v, str):
                out[np] = v
            else:
                out.update(flat(v, np))
    return out


def unflat(d: dict[str, str]) -> dict:
    root: dict = {}
    for k, v in d.items():
        parts = k.split(".")
        cur = root
        for part in parts[:-1]:
            cur = cur.setdefault(part, {})
        cur[parts[-1]] = v
    return root


def polish_en_notes() -> None:
    path = ROOT / "packages/shared/locales/en/notes.json"
    data = json.loads(path.read_text())
    fe = flat(data)
    cjk_before = sum(1 for v in fe.values() if re.search(r"[\u4e00-\u9fff]", v))
    for k, v in fe.items():
        s = v
        if s.startswith("[zh] "):
            s = s[5:]
        s = (
            s.replace("：", ": ")
            .replace("，", ", ")
            .replace("（", "(")
            .replace("）", ")")
            .replace("／", "/")
            .replace("、", ", ")
            .replace("；", "; ")
            .replace("「", '"')
            .replace("」", '"')
        )
        s = re.sub(r"[\u4e00-\u9fff]+", "", s)
        s = re.sub(r"\s+", " ", s).strip()
        s = re.sub(r"\s+([,.;:!?])", r"\1", s)
        fe[k] = s
    path.write_text(json.dumps(unflat(fe), ensure_ascii=False, indent=2) + "\n")
    cjk_after = sum(1 for v in fe.values() if re.search(r"[\u4e00-\u9fff]", v))
    print(f"en notes: CJK leaves {cjk_before} → {cjk_after}")
    print("  sample auto.n0001:", fe.get("auto.n0001"))
    print("  sample auto.t0001:", fe.get("auto.t0001"))



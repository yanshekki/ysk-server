def to_cn(s: str) -> str:
    if not isinstance(s, str):
        return s  # type: ignore[return-value]
    for a, b in sorted(MULTI, key=lambda x: -len(x[0])):
        s = s.replace(a, b)
    return s.translate(CHARS)


def walk(o: object, fn) -> object:
    if isinstance(o, str):
        return fn(o)
    if isinstance(o, list):
        return [walk(x, fn) for x in o]
    if isinstance(o, dict):
        return {k: walk(v, fn) for k, v in o.items()}
    return o


